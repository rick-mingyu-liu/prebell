#!/usr/bin/env bash
# One-off: generate a cover scene image for each post published before scenes
# existed (cover_key IS NULL), upload it to R2 as covers/<slug>.<ext> and write
# the matching UPDATE statements to backfill-scenes.sql. It writes to R2 but
# never runs the SQL. One Workers AI generation per post, no retries. Run from
# the repo root. Needs CF_AI_TOKEN in the environment or in
# crates/generator/.dev.vars; CF_ACCOUNT_ID defaults to crates/generator/wrangler.toml.
set -euo pipefail
for c in jq curl base64 xxd; do
  command -v "$c" >/dev/null || { echo "$c is required" >&2; exit 1; }
done

OUT=backfill-scenes.sql
IMG_DIR=backfill-scenes
BUCKET=prebell-facts
MODEL='@cf/black-forest-labs/flux-1-schnell'
WRANGLER=(pnpm exec wrangler)

# Read a KEY=value line without sourcing the file.
dev_var() { sed -n "s/^$1=//p" crates/generator/.dev.vars 2>/dev/null | tail -n1; }
CF_AI_TOKEN=${CF_AI_TOKEN:-$(dev_var CF_AI_TOKEN)}
CF_ACCOUNT_ID=${CF_ACCOUNT_ID:-$(sed -n 's/^CF_ACCOUNT_ID *= *"\(.*\)"/\1/p' crates/generator/wrangler.toml)}
[[ -n $CF_AI_TOKEN ]] || { echo "CF_AI_TOKEN not set and not in crates/generator/.dev.vars" >&2; exit 1; }
[[ -n $CF_ACCOUNT_ID ]] || { echo "CF_ACCOUNT_ID not found in crates/generator/wrangler.toml" >&2; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

cargo build -q -p prebell-core --bin cover-lines
BIN=$PWD/target/debug/cover-lines
mkdir -p "$IMG_DIR"
: >"$OUT"

# Wrangler config lives in crates/generator; paths below are relative to it.
cd crates/generator
"${WRANGLER[@]}" d1 execute prebell --remote --json --command \
  "SELECT id, slug, content_type, facts_r2_key FROM posts WHERE cover_key IS NULL AND facts_r2_key IS NOT NULL" \
  >"$TMP/rows.json"
cd ../..

jq -e -r '.[0].results[] | [.id, .slug, .content_type, .facts_r2_key] | @tsv' "$TMP/rows.json" >"$TMP/rows.tsv" || true
if [[ ! -s $TMP/rows.tsv ]]; then
  echo "no posts without a cover scene (or the D1 reply had no rows)"
  exit 0
fi
rows=0 written=0 skipped=0

skip() { echo "skip post $id ($slug): $1" >&2; skipped=$((skipped + 1)); }

while IFS=$'\t' read -r id slug kind key; do
  rows=$((rows + 1))
  if [[ ! $id =~ ^[0-9]+$ || ! $slug =~ ^[A-Za-z0-9._-]+$ ]]; then
    skip "unexpected id or slug"; continue
  fi
  facts="$TMP/facts.json" resp="$TMP/resp.json" img="$TMP/img"
  rm -f "$facts" "$resp" "$img"

  if ! (cd crates/generator && "${WRANGLER[@]}" r2 object get "$BUCKET/$key" --file "$facts" --remote >/dev/null 2>"$TMP/err"); then
    skip "facts download failed: $(tail -n1 "$TMP/err")"; continue
  fi
  if ! prompt=$("$BIN" --prompt "$kind" "$facts" 2>"$TMP/err"); then
    skip "no scene prompt: $(tail -n1 "$TMP/err")"; continue
  fi

  # The token goes to curl on stdin, not argv, so it never shows in `ps`.
  jq -n --arg p "$prompt" '{prompt: $p, steps: 4}' >"$TMP/body.json"
  status=$(printf 'Authorization: Bearer %s\n' "$CF_AI_TOKEN" | curl -sS --max-time 120 -o "$resp" -w '%{http_code}' \
    -H @- -H 'Content-Type: application/json' --data @"$TMP/body.json" \
    "https://api.cloudflare.com/client/v4/accounts/$CF_ACCOUNT_ID/ai/run/$MODEL" 2>"$TMP/err") || status=000
  if [[ $status != 2* ]]; then
    reason=$(jq -r '[.errors[]?.message] | join("; ")' "$resp" 2>/dev/null || true)
    skip "generation failed (http $status): ${reason:-$(tail -n1 "$TMP/err")}"; continue
  fi
  if ! jq -e -r '.result.image // empty' "$resp" | base64 -d >"$img" 2>/dev/null || [[ ! -s $img ]]; then
    skip "generation returned no image"; continue
  fi

  case $(head -c 4 "$img" | xxd -p) in
    ffd8ff*) ext=jpg mime=image/jpeg ;;
    89504e47) ext=png mime=image/png ;;
    *) skip "generated bytes are not JPEG or PNG"; continue ;;
  esac
  file="$IMG_DIR/$slug.$ext"
  cp "$img" "$file"

  r2key="covers/$slug.$ext"
  if ! up=$(cd crates/generator && "${WRANGLER[@]}" r2 object put "$BUCKET/$r2key" --file "../../$file" --content-type "$mime" --remote 2>&1) \
     || [[ $up != *"Upload complete"* ]]; then
    skip "upload failed: $(tail -n1 <<<"$up")"; continue
  fi

  echo "UPDATE posts SET cover_key = '$r2key' WHERE id = $id;" >>"$OUT"
  echo "post $id ($slug): $r2key, $(wc -c <"$file" | tr -d ' ') bytes"
  written=$((written + 1))
done <"$TMP/rows.tsv"

echo "posts without a scene: $rows; uploaded: $written; skipped: $skipped"
echo "SQL written to $OUT (not executed). To apply it:"
echo "  cd crates/generator && pnpm exec wrangler d1 execute prebell --remote --file ../../$OUT"
